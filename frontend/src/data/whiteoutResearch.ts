export const researchByKey = new Map(whiteoutResearch.map(n => [n.key, n]));

/** Total power a node is worth if taken from `from` up to `to` inclusive. */
export const researchPowerBetween = (node: ResearchNode, from: number, to: number) =>
  node.levels.filter(l => l.level > from && l.level <= to).reduce((s, l) => s + l.power, 0);

/* ------------------------------------------------------------------ *
 * Tiers
 *
 * Node names carry a Roman numeral tier, "Tooling Up I" through
 * "Ward Expansion VII". Players progress roughly tier by tier, so asking which
 * tier they have finished is a far kinder question than asking about all 191
 * nodes one at a time.
 * ------------------------------------------------------------------ */

const ROMAN: Record<string, number> = {
  I: 1, II: 2, III: 3, IV: 4, V: 5, VI: 6, VII: 7, VIII: 8, IX: 9, X: 10,
};

export const researchTier = (node: ResearchNode): number => {
  const last = node.name.trim().split(/\s+/).pop() ?? '';
  return ROMAN[last.toUpperCase()] ?? 0;
};

export const MAX_RESEARCH_TIER = Math.max(...whiteoutResearch.map(researchTier));

/**
 * Marks every node at or below `tier` as fully researched, which is what
 * "I have finished tier III" means in practice.
 */
export const completedThroughTier = (
  tiers: Record<ResearchTree, number>
): Record<string, number> => {
  const out: Record<string, number> = {};
  for (const node of whiteoutResearch) {
    const t = researchTier(node);
    if (t > 0 && t <= (tiers[node.tree] ?? 0)) {
      out[node.key] = node.levels[node.levels.length - 1]?.level ?? 0;
    }
  }
  return out;
};
