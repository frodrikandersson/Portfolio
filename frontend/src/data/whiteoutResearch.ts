// Whiteout Survival Research Center tech tree.
//
// 191 nodes across the Growth, Economy and Battle trees, 720 levels in total.
// Every level costs Steel, which is why Steel is a resource in its own right.
//
// Each level carries its own cost, time, power and requirements. Requirements
// are of two kinds: other research nodes at a given level, and a minimum
// Research Center level. The optimiser uses both, so it never proposes a node
// the player cannot actually start.
//
// Scraped from wostools.net's research calculator, which embeds the whole table
// as JSON. Not verified against the game.
//
// EDIT FREELY: nothing in the optimiser hardcodes a number.

export type ResearchTree = 'Growth' | 'Economy' | 'Battle';

export const RESEARCH_TREES: ResearchTree[] = ['Growth', 'Economy', 'Battle'];

export interface ResearchLevel {
  level: number;
  /** Power gained by taking this single level. */
  power: number;
  /** How much the node's stat improves at this level. */
  statAddition: number;
  seconds: number;
  cost: {
    meat: number;
    wood: number;
    coal: number;
    iron: number;
    steel: number;
  };
  /** Other nodes that must already be at the given level. */
  requiresResearch: { key: string; level: number }[];
  /** Minimum building levels, keyed by building slug. */
  requiresBuildings: { slug: string; level: number }[];
}

export interface ResearchNode {
  key: string;
  tree: ResearchTree;
  name: string;
  /** What the node improves, e.g. "construction-speed". */
  stat: string;
  /** Set when the node only affects one troop type. */
  troopType: string | null;
  /** Display row in the in-game tree, useful for ordering. */
  row: number;
  levels: ResearchLevel[];
}

